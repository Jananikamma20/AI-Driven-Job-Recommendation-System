# =========================================================
# YEAR PATTERN
# =========================================================

# Matches years from 1900 to 2099

YEAR = r"(?:19\d{2}|20\d{2})"


# =========================================================
# MONTH NUMBER
# =========================================================

# Matches:
# 01
# 02
# ...
# 12

MONTH = r"(?:0?[1-9]|1[0-2])"


# =========================================================
# DAY
# =========================================================

DAY = r"(?:0?[1-9]|[12][0-9]|3[01])"


# =========================================================
# MONTH NAME
# =========================================================

MONTH_NAME = (
    r"(?:Jan(?:uary)?|"
    r"Feb(?:ruary)?|"
    r"Mar(?:ch)?|"
    r"Apr(?:il)?|"
    r"May|"
    r"Jun(?:e)?|"
    r"Jul(?:y)?|"
    r"Aug(?:ust)?|"
    r"Sep(?:tember)?|"
    r"Oct(?:ober)?|"
    r"Nov(?:ember)?|"
    r"Dec(?:ember)?)"
)


# =========================================================
# PRESENT WORDS
# =========================================================

PRESENT = (
    r"(?:Present|Current|Till\s+Date|Till\s+Now|Ongoing)"
)


# =========================================================
# DATE FORMATS
# =========================================================

DATE_PATTERNS = {

    # -----------------------------------------
    # 08/2020
    # -----------------------------------------

    "MM_YYYY_SLASH":

    rf"\b{MONTH}/{YEAR}\b",

    # -----------------------------------------
    # 08-2020
    # -----------------------------------------

    "MM_YYYY_DASH":

    rf"\b{MONTH}-{YEAR}\b",

    # -----------------------------------------
    # 08.2020
    # -----------------------------------------

    "MM_YYYY_DOT":

    rf"\b{MONTH}\.{YEAR}\b",

    # -----------------------------------------
    # 08/15/2020
    # -----------------------------------------

    "MM_DD_YYYY":

    rf"\b{MONTH}/{DAY}/{YEAR}\b",

    # -----------------------------------------
    # 15/08/2020
    # -----------------------------------------

    "DD_MM_YYYY":

    rf"\b{DAY}/{MONTH}/{YEAR}\b",

    # -----------------------------------------
    # Jan 2020
    # January 2020
    # -----------------------------------------

    "MONTH_YEAR":

    rf"\b{MONTH_NAME}\s+{YEAR}\b",

    # -----------------------------------------
    # 2020
    # -----------------------------------------

    "YEAR_ONLY":

    rf"\b{YEAR}\b",

    # -----------------------------------------
    # 2020-2022
    # 2020 to 2022
    # -----------------------------------------

    "YEAR_RANGE":

    rf"\b{YEAR}\s*(?:-|to)\s*{YEAR}\b",

    # -----------------------------------------
    # Jan 2020 - Mar 2022
    # -----------------------------------------

    "MONTH_YEAR_RANGE":

    rf"\b{MONTH_NAME}\s+{YEAR}\s*(?:-|to)\s*{MONTH_NAME}\s+{YEAR}\b",

    # -----------------------------------------
    # 08/2020 - 10/2022
    # -----------------------------------------

    "NUMERIC_RANGE":

    rf"\b{MONTH}/{YEAR}\s*(?:-|to)\s*{MONTH}/{YEAR}\b",

    # -----------------------------------------
    # 2020 - Present
    # -----------------------------------------

    "YEAR_PRESENT":

    rf"\b{YEAR}\s*(?:-|to)\s*{PRESENT}\b",

    # -----------------------------------------
    # Jan 2022 - Present
    # -----------------------------------------

    "MONTH_PRESENT":

    rf"\b{MONTH_NAME}\s+{YEAR}\s*(?:-|to)\s*{PRESENT}\b",

    # -----------------------------------------
    # 08/2022 - Present
    # -----------------------------------------

    "NUMERIC_PRESENT":

    rf"\b{MONTH}/{YEAR}\s*(?:-|to)\s*{PRESENT}\b",

    # -----------------------------------------
    # Aug'21
    # Jan'19
    # -----------------------------------------

    "SHORT_MONTH_APOSTROPHE":

    rf"\b(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)'?\d{{2}}\b",

    # -----------------------------------------
    # 2020/08
    # -----------------------------------------

    "YYYY_MM":

    rf"\b{YEAR}/{MONTH}\b",

    # -----------------------------------------
    # August, 2020
    # -----------------------------------------

    "MONTH_COMMA_YEAR":

    rf"\b{MONTH_NAME},\s*{YEAR}\b",

}